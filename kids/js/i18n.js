const DICTS = { ru, en };
export const LANGS = [['ru', 'Русский'], ['en', 'English']];

function detect() {
  try { const s = localStorage.getItem(LANG_KEY); if (DICTS[s]) return s; } catch (err) {}
  return (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
}
export let lang = detect();
document.documentElement.lang = lang;

export function setLang(l) {
  if (!DICTS[l]) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch (err) {}
}

export function t(key, vars = {}) {
  let s = DICTS[lang][key] ?? DICTS.en[key];
  if (s === undefined) { console.warn('i18n: missing', key); return key; }
  if (Array.isArray(s)) s = s[Math.floor(Math.random() * s.length)];
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}
export const raw = key => DICTS[lang][key] ?? DICTS.en[key];

export function pw(n, word) {
  const forms = DICTS[lang].plurals[word];
  if (lang === 'ru') {
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return forms[2];
    if (b === 1) return forms[0];
    if (b >= 2 && b <= 4) return forms[1];
    return forms[2];
  }
  return Math.abs(n) === 1 ? forms[0] : forms[1];
}

