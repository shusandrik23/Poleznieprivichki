// Copies the fonts the app uses from node_modules/@fontsource into fonts/ and writes fonts.css,
// so nikud renders correctly offline (inside the Android app) without Google Fonts.
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';

const FACES = [
  ['Frank Ruhl Libre', 'frank-ruhl-libre', ['hebrew'], [500, 700]],
  ['Rubik', 'rubik', ['hebrew', 'latin'], [400, 500, 700]],
];
const RANGES = { hebrew: 'U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F',
                 latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD' };
mkdirSync('fonts', { recursive: true });
let css = '/* generated by tools/copy-fonts.mjs */\n';
for (const [family, pkg, subsets, weights] of FACES) for (const sub of subsets) for (const w of weights) {
  const file = `${pkg}-${sub}-${w}-normal.woff2`;
  copyFileSync(`node_modules/@fontsource/${pkg}/files/${file}`, `fonts/${file}`);
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(fonts/${file}) format("woff2");unicode-range:${RANGES[sub]}}\n`;
}
writeFileSync('fonts.css', css);
console.log('fonts copied');
