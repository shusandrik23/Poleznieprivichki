    fun profile(d: Dosha, kid: Boolean): DoshaProfile = if (kid) kids.getValue(d) else adults.getValue(d)

    /** Короткое описание результата: для одной доши — её описание, для смешанных — отдельный текст. */
    fun summary(r: DoshaResult, kid: Boolean): String = when (r.leading.size) {
        1 -> profile(r.leading[0], kid).about
        2 -> pairText(r.leading.toSet(), kid)
        else -> if (kid) KID_TRI else ADULT_TRI
    }

    /** Совет по сезонам для смешанных типов. */
    fun seasonTip(r: DoshaResult, kid: Boolean): String? {
        if (r.leading.size < 2) return null
        val parts = r.leading.sortedBy { it.ordinal }.map {
            when (it) {
                Dosha.VATA -> "осенью и в начале зимы, в холод и ветер — советам для Ваты"
                Dosha.PITTA -> "летом и в жару — советам для Питты"
                Dosha.KAPHA -> "весной и в сырую погоду — советам для Капхи"
            }
        }
        val who = if (kid) "Тебе подходят советы сразу для нескольких дош. Больше следуй" else
            "Вам подходят советы сразу для нескольких дош. Больше следуйте"
        return "$who " + parts.joinToString(", ") + "."
    }

